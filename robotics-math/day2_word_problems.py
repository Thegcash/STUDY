# Day 2: robot word problems

# Problem 1: speed = distance / time
speed = (0.7 - 0.1) / 3            # m/s

# Problem 2: time = distance / speed
time = 6 / 0.5                     # s

# Problem 3: percent left = (reading - empty) / (full - empty) * 100
percent = (51.5 - 44) / (54 - 44) * 100

# Problem 4: angle = turning speed * time
angle = 2 * 1.5                    # rad

print(speed, time, percent, angle)
